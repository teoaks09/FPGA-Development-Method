#!/usr/bin/env python3
"""Create (or extend) an FPGA project from the fpga-method kit.

The project gets the canonical tree of manifest.toml filtered by its profile:
  weight       light | standard | comprehensive          (how much process and documentation)
  team         L1 | L2 | L3 | L4                          (who does the work: cost level)
  deliverables code (always) + ip, board, hwtest, sw       (what is delivered)
  options      xilinx_ip, hls, wiki                       (extra canonical folders)

Examples
  new_project.py --name uart_lite --dest ~/work/uart_lite --weight light --team L4 \
      --deliver ip --prefix ul --part xczu9eg-ffvb1156-2-e --clock-mhz 100 --features uart:simple
  new_project.py --name eth_stack --dest ~/work/eth --weight comprehensive --team L2 \
      --deliver ip,board,hwtest,sw --with xilinx_ip,wiki --board zcu102 --prefix es \
      --part xczu9eg-ffvb1156-2-e --clock-mhz 322 --features arp:medium,udp:medium,tcp:hard
  new_project.py --existing --dest ~/work/uart_lite --weight standard --team L2 ...   (grow a project)

Nothing is overwritten in --existing mode except the profile values in project.toml/AGENTS.md.
"""
import argparse
import datetime
import os
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

KIT = Path(__file__).resolve().parents[1]
TEMPLATE = KIT / "template"
WEIGHTS = ["light", "standard", "comprehensive"]
TEAMS = ["L1", "L2", "L3", "L4"]
DELIVERABLES = ["code", "ip", "board", "hwtest", "sw"]
OPTIONS = ["xilinx_ip", "hls", "wiki"]
CLAUDE_MODELS = {"opus", "sonnet", "haiku"}
# Kit-owned files that are regenerated by --existing; their project block is carried over.
REGENERATED = {"AGENTS.md", "CLAUDE.md", "Makefile"}
PROJECT_BLOCK = re.compile(r"^[^\n]*project:begin[^\n]*\n.*?^[^\n]*project:end[^\n]*$", re.M | re.S)
MARKER = re.compile(r"^\s*(?:<!--|#)\s*@(if|end)\b\s*(.*?)\s*(?:-->)?\s*$")
PLACEHOLDER = re.compile(r"\{\{([A-Z_]+)\}\}")


# ------------------------------------------------------------------------------------ profile
def condition_holds(clause: str, ctx: dict) -> bool:
    """clause: 'key=a,b' or 'key=a|key2=b' (OR). key in weight, team, deliverable, option."""
    for alternative in clause.split("|"):
        key, _, values = alternative.partition("=")
        wanted = {v.strip() for v in values.split(",")}
        have = ctx[key.strip()]
        if (wanted & have) if isinstance(have, set) else (have in wanted):
            return True
    return False


def selected(entry: dict, ctx: dict) -> bool:
    return all(condition_holds(clause, ctx) for clause in entry.get("when", []))


def render_conditionals(text: str, ctx: dict, source: str) -> str:
    output, stack = [], []
    for number, line in enumerate(text.splitlines(keepends=True), 1):
        marker = MARKER.match(line)
        if marker and marker.group(1) == "if":
            stack.append(condition_holds(marker.group(2), ctx))
            continue
        if marker and marker.group(1) == "end":
            if not stack:
                sys.exit(f"{source}:{number}: @end without @if")
            stack.pop()
            continue
        if all(stack):
            output.append(line)
    if stack:
        sys.exit(f"{source}: unterminated @if")
    return "".join(output)


def render_placeholders(text: str, values: dict, source: str) -> str:
    missing = sorted({m for m in PLACEHOLDER.findall(text) if m not in values})
    if missing:
        sys.exit(f"{source}: no value for placeholder(s) {', '.join(missing)}")
    return PLACEHOLDER.sub(lambda m: str(values[m.group(1)]), text)


# ------------------------------------------------------------------------------------ manifest
def load_manifest() -> list:
    entries = tomllib.loads((KIT / "manifest.toml").read_text())["path"]
    covered = set()
    for entry in entries:
        source = TEMPLATE / entry["path"]
        if not source.exists():
            sys.exit(f"manifest entry without template: {entry['path']}")
        if source.is_dir():
            covered |= {p for p in source.rglob("*") if p.is_file()}
        else:
            covered.add(source)
    uncovered = sorted(p.relative_to(TEMPLATE).as_posix() for p in TEMPLATE.rglob("*")
                       if p.is_file() and p not in covered)
    if uncovered:
        sys.exit("template files not covered by manifest.toml:\n  " + "\n  ".join(uncovered))
    return entries


def destination_name(relative: str, values: dict) -> str:
    return relative.replace("__BOARD__", values["BOARD"]).replace("{{PREFIX}}", values["PREFIX"])


def copy_entry(entry: dict, ctx: dict, values: dict, dest: Path, existing: bool, log: list) -> None:
    source = TEMPLATE / entry["path"]
    files = [p for p in source.rglob("*") if p.is_file()] if source.is_dir() else [source]
    if source.is_dir():
        target_dir = dest / destination_name(entry["path"], values)
        target_dir.mkdir(parents=True, exist_ok=True)
        for empty in [d for d in source.rglob("*") if d.is_dir() and not any(d.iterdir())] + \
                     ([source] if not files else []):
            keep = dest / destination_name(empty.relative_to(TEMPLATE).as_posix(), values) / ".gitkeep"
            keep.parent.mkdir(parents=True, exist_ok=True)
            keep.touch()
    for file in files:
        relative = file.relative_to(TEMPLATE).as_posix()
        target = dest / destination_name(relative, values)
        text = render_placeholders(render_conditionals(file.read_text(), ctx, relative), values, relative)
        if target.exists() and existing:
            if relative not in REGENERATED:
                log.append(f"kept     {target.relative_to(dest)}")
                continue
            old_block = PROJECT_BLOCK.search(target.read_text())
            if old_block:
                text = PROJECT_BLOCK.sub(lambda _: old_block.group(0), text, count=1)
            log.append(f"updated  {target.relative_to(dest)} (project block kept)")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
        if os.access(file, os.X_OK):
            target.chmod(0o755)
        log.append(f"created  {target.relative_to(dest)}")


# ------------------------------------------------------------------------------------ agents
def opencode_permissions(writable: list) -> list:
    lines = ["permission:", "  edit:", '    "*": deny']
    allows = [p for p in writable if not p.startswith("!")]
    denies = [p[1:] for p in writable if p.startswith("!")]
    lines += [f'    "{p}": allow' for p in allows] + [f'    "{p}": deny' for p in denies]
    lines += ["  bash:", '    "*": ask', '    "make *": allow', '    "python3 flow/*": allow',
              '    "git status*": allow', '    "git diff*": allow', '    "git add*": allow',
              '    "git commit*": allow', '    "git checkout*": allow', '    "flow/git/commit.sh*": allow',
              '    "git push*": deny', "  webfetch: deny"]
    return lines


def render_agents(ctx: dict, config: dict, dest: Path, log: list) -> list:
    roles = tomllib.loads((KIT / "agents/roles.toml").read_text())
    ids, team, rows = config["models"], ctx["team"], []
    wanted = set()
    for role, spec in roles.items():
        if ctx["weight"] not in spec["weights"]:
            continue
        model_key, effort = spec["model"][team], spec["effort"][team]
        if model_key == "none":
            continue
        body = (KIT / "agents/roles" / f"{role}.md").read_text().rstrip() + "\n"
        writable = "\n".join(f"- not `{p[1:]}`" if p.startswith("!") else f"- `{p}`" for p in spec["writable"])
        body += f"\n## Writable paths\n{writable}\n"
        if spec.get("cannot_read"):
            body += "\n## Do not read\n" + "\n".join(f"- `{p}`" for p in spec["cannot_read"]) + "\n"
        if model_key in CLAUDE_MODELS:
            path = dest / ".claude/agents" / f"{role}.md"
            front = ["---", f"name: {role}", f"description: {spec['description']}", f"model: {ids[model_key]}"]
            if effort != "default":
                front.append(f"effort: {effort}")
            text = "\n".join(front + ["---", ""]) + body
            text += ("\nWritable paths are not enforced by Claude Code for subagents: stay inside them; "
                     "`make check-locks` and the reviewer check.\n")
            tool = "Claude Code"
        else:
            path = dest / ".opencode/agents" / f"{role}.md"
            front = ["---", f"description: {spec['description']}", "mode: primary", f"model: {ids[model_key]}",
                     f"steps: {80 if role in ('rtl-designer', 'verification') else 40}"]
            if effort == "low":
                front.append("reasoningEffort: low   # PILOT: check the platform accepts it")
            text = "\n".join(front + opencode_permissions(spec["writable"]) + ["---", ""]) + body
            tool = "opencode"
        rows.append((role, tool, config["names"].get(model_key, model_key), effort, spec["description"]))
        write_generated(path, text, dest, log)
        wanted.add(path)
    if team in ("L2", "L3"):
        senior = (KIT / "agents/roles/senior-engineer.md").read_text()
        text = ("---\nname: senior-engineer\ndescription: Takes over escalated task cards and, in L2, features "
                f"tagged difficulty hard.\nmodel: {ids['sonnet']}\neffort: high\n---\n\n{senior}")
        write_generated(dest / ".claude/agents/senior-engineer.md", text, dest, log)
        wanted.add(dest / ".claude/agents/senior-engineer.md")
        rows.append(("senior-engineer", "Claude Code", config["names"]["sonnet"], "high",
                     "Escalations (free model failed max_attempts); L2 hard features"))
    # A role that moved to the other tool (or is no longer used) leaves no stale agent file behind.
    for folder in (dest / ".claude/agents", dest / ".opencode/agents"):
        for stale in sorted(folder.glob("*.md")) if folder.exists() else []:
            if stale not in wanted:
                stale.unlink()
                log.append(f"removed  {stale.relative_to(dest)} (role not on this tool in the new profile)")
    return rows


def write_generated(path: Path, text: str, dest: Path, log: list) -> None:
    """Agent files are derived from the kit's roles.toml and always regenerated."""
    state = "updated " if path.exists() else "created "
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    log.append(f"{state} {path.relative_to(dest)}")


# ------------------------------------------------------------------------------------ main
def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", required=True)
    parser.add_argument("--dest", type=Path)
    parser.add_argument("--summary", default="<one paragraph: what this project builds>")
    parser.add_argument("--weight", choices=WEIGHTS, required=True)
    parser.add_argument("--team", choices=TEAMS, required=True)
    parser.add_argument("--deliver", default="", help="comma list of: ip,board,hwtest,sw (code is implied)")
    parser.add_argument("--with", dest="options", default="", help="comma list of: xilinx_ip,hls,wiki")
    parser.add_argument("--prefix", required=True, help="module name prefix, e.g. ul")
    parser.add_argument("--part", required=True)
    parser.add_argument("--clock-mhz", type=int, default=100)
    parser.add_argument("--board", default="", help="board folder name (deliverable board)")
    parser.add_argument("--features", default="", help="comma list name[:difficulty]")
    parser.add_argument("--dispatch", choices=["manual", "auto"])
    parser.add_argument("--kit-config", type=Path, default=KIT / "kit_config.toml")
    parser.add_argument("--existing", action="store_true", help="extend an existing project, never overwrite")
    parser.add_argument("--git", action="store_true", help="git init + first commit (new projects)")
    parser.add_argument("--with-ross", action="store_true", help="run flow/tools/ross_setup.sh (network)")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    args.dest = (args.dest or Path.cwd() / args.name).expanduser().resolve()
    return args


def build_context(args: argparse.Namespace) -> dict:
    deliverables = {"code"} | {d.strip() for d in args.deliver.split(",") if d.strip()}
    options = {o.strip() for o in args.options.split(",") if o.strip()}
    for item, allowed in ((deliverables, DELIVERABLES), (options, OPTIONS)):
        unknown = item - set(allowed)
        if unknown:
            sys.exit(f"unknown value(s): {', '.join(sorted(unknown))}")
    if "board" in deliverables and not args.board:
        sys.exit("--board is required for deliverable 'board'")
    if args.team == "L4" and args.weight == "comprehensive":
        print("note: L4 with comprehensive weight - the free models carry all documentation work")
    return {"weight": args.weight, "team": args.team, "deliverable": deliverables, "option": options}


def build_values(args, ctx: dict, kit: dict) -> dict:
    tools, models = kit["tools"], kit["models"]
    version = tools["ross_version"]
    mcp_binary = str(Path(tools["ross_mcp_root"]).expanduser() / version /
                     tools["ross_mcp_binary"].format(version=version))
    ordered = [d for d in DELIVERABLES if d in ctx["deliverable"]]
    profile = f"{ctx['weight']} × {ctx['team']} × {{{', '.join(ordered)}}}"
    if ctx["option"]:
        profile += f" + {', '.join(sorted(ctx['option']))}"
    ids = {k: v for k, v in models.items() if isinstance(v, str)}
    models_toml = "[models.ids]\n" + "\n".join(f'{k} = "{v}"' for k, v in ids.items())
    models_toml += "\n\n[models.names]\n" + "\n".join(f'{k} = "{v}"' for k, v in models["names"].items())
    wiki = ctx["weight"] != "light"
    return {
        "PROJECT": args.name, "SUMMARY": args.summary, "PROFILE_LINE": profile,
        "WEIGHT": ctx["weight"], "TEAM": ctx["team"], "DELIVERABLES": ", ".join(ordered),
        "DELIVERABLES_TOML": ", ".join(f'"{d}"' for d in ordered),
        "KIT_VERSION": (KIT / "VERSION").read_text().strip(), "DATE": datetime.date.today().isoformat(),
        "DISPATCH": args.dispatch or kit["defaults"]["dispatch"], "MAX_ATTEMPTS": kit["defaults"]["max_attempts"],
        "WIKI_HINT": " (compiled knowledge: llm/wiki/index.md)" if wiki else "",
        "VIVADO_VERSION": tools["vivado_version"], "VIVADO_PATH": tools["vivado_path"],
        "ROSS_VERSION": version, "VERILATOR_VERSION": tools["verilator_version"],
        "ROSS_MCP_BINARY": mcp_binary, "AMD_DOC_SEARCH_URL": tools["amd_doc_search_url"],
        "PART": args.part, "PREFIX": args.prefix, "CLOCK_MHZ": args.clock_mhz, "BOARD": args.board or "board",
        "IP_VENDOR": kit["organisation"]["ip_vendor"], "MODELS_TOML": models_toml,
        "LOCKS_TOML": '"docs/input/**"', "WHERE_TABLE": "{{WHERE_TABLE}}", "ROLE_TABLE": "{{ROLE_TABLE}}",
    }


def finish_agents_md(dest: Path, entries: list, ctx: dict, rows: list) -> None:
    where = ["| Path | Content |", "|---|---|"]
    for entry in entries:
        if "where" in entry and selected(entry, ctx):
            shown = entry.get("show", entry["path"]).replace("__BOARD__", "<board>")
            text = entry["where"][0].upper() + entry["where"][1:]
            where.append(f"| `{shown}` | {text} |")
    roles = ["| Role | Tool | Model | Effort | Task |", "|---|---|---|---|---|"]
    roles += [f"| {r} | {t} | {m} | {e} | {d} |" for r, t, m, e, d in rows]
    if ctx["team"] == "L1":
        roles.append("| (main session) | Claude Code | Opus | high | System view, planning, dispatch to subagents |")
    agents = dest / "AGENTS.md"
    text = agents.read_text()
    if "{{WHERE_TABLE}}" not in text and "## Where is what" in text:
        return  # existing project: user-maintained tables are kept
    agents.write_text(text.replace("{{WHERE_TABLE}}", "\n".join(where)).replace("{{ROLE_TABLE}}", "\n".join(roles)))


def update_profile_existing(dest: Path, values: dict) -> None:
    project = dest / "project.toml"
    text = project.read_text()
    for key, value in (("weight", values["WEIGHT"]), ("team", values["TEAM"])):
        text = re.sub(rf'^{key} = "[^"]*"', f'{key} = "{value}"', text, flags=re.M)
    text = re.sub(r"^deliverables = \[.*\]", f"deliverables = [{values['DELIVERABLES_TOML']}]", text, flags=re.M)
    project.write_text(text)
    agents = dest / "AGENTS.md"
    agents.write_text(re.sub(r"^`[^`\n]*×[^`\n]*`$", f"`{values['PROFILE_LINE']}`", agents.read_text(), flags=re.M))


def main() -> int:
    args = parse_args()
    kit = tomllib.loads(args.kit_config.read_text())
    ctx = build_context(args)
    values = build_values(args, ctx, kit)
    entries = load_manifest()
    chosen = [e for e in entries if selected(e, ctx)]
    if args.dry_run:
        print(f"profile: {values['PROFILE_LINE']}")
        for entry in chosen:
            print("  " + destination_name(entry["path"], values))
        return 0
    if args.dest.exists() and any(args.dest.iterdir()) and not args.existing:
        sys.exit(f"{args.dest} is not empty (use --existing to extend a project)")
    args.dest.mkdir(parents=True, exist_ok=True)
    log = []
    for entry in chosen:
        copy_entry(entry, ctx, values, args.dest, args.existing, log)
    config = {"models": {k: v for k, v in kit["models"].items() if isinstance(v, str)},
              "names": kit["models"]["names"]}
    rows = render_agents(ctx, config, args.dest, log)
    if args.existing:
        update_profile_existing(args.dest, values)
    finish_agents_md(args.dest, entries, ctx, rows)

    for feature in [f.strip() for f in args.features.split(",") if f.strip()]:
        name, _, difficulty = feature.partition(":")
        command = [sys.executable, str(args.dest / "flow/gen/new_feature.py"), name,
                   "--difficulty", difficulty or "medium"]
        result = subprocess.run(command, cwd=args.dest, capture_output=True, text=True)
        log += [f"feature  {line}" for line in result.stdout.splitlines()]
        if result.returncode:
            sys.exit(result.stderr)

    leftovers = [p.relative_to(args.dest).as_posix() for p in args.dest.rglob("*")
                 if p.is_file() and p.suffix in {".md", ".toml", ".json", ".tcl", ".sh", ".py", ""}
                 and PLACEHOLDER.search(p.read_text(errors="ignore"))]
    if leftovers:
        print("WARNING: unresolved placeholders in: " + ", ".join(leftovers))

    if args.git and not (args.dest / ".git").exists():
        subprocess.run(["git", "init", "-q", "-b", "main"], cwd=args.dest, check=True)
        subprocess.run(["git", "add", "-A"], cwd=args.dest, check=True)
        subprocess.run(["git", "commit", "-q", "-m", f"Project setup from fpga-method {values['KIT_VERSION']}",
                        "-m", f"Profile: {values['PROFILE_LINE']}"], cwd=args.dest, check=True)
    if args.with_ross:
        subprocess.run([str(args.dest / "flow/tools/ross_setup.sh")], cwd=args.dest, check=False)

    created = sum(1 for line in log if line.startswith("created"))
    kept = sum(1 for line in log if line.startswith("kept"))
    for line in log:
        if not line.startswith("created") or "--verbose" in sys.argv:
            print(line)
    print(f"profile: {values['PROFILE_LINE']}")
    print(f"NEW_PROJECT_RESULT: PASS dest={args.dest} created={created} kept={kept}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
